package com.paulorchard.islandcraft.equipmentofarrakis.hud;

import com.hypixel.hytale.server.core.entity.entities.player.hud.CustomUIHud;
import com.hypixel.hytale.server.core.ui.Anchor;
import com.hypixel.hytale.server.core.ui.Value;
import com.hypixel.hytale.server.core.ui.builder.UICommandBuilder;
import com.hypixel.hytale.server.core.universe.PlayerRef;

/**
 * The four bars of one player: Power over Health on the left, Heat Exposure over Water on the right, above the hotbar. Read only: it
 * shows what the game and the Water mod hold and changes nothing. The structure is
 * {@code Common/UI/Custom/Hud/Equipment_of_Arrakis/Hud/Arrakis_Hud.ui} (generated by tools/assets/hud/make_hud.js, its comments
 * explain the scaling); every position, size and colour is set again from {@link HudConfig} when the document is built.
 *
 * <p>Each screen row is split in two halves of equal FlexWeight, so the middle of the screen (the middle of the hotbar, which the client
 * draws centred) is exact at every resolution; offsets from it are in the same virtual pixels as the hotbar, so the bars keep their
 * place against it. A bar is a track of an empty part and a fill part that share its length by FlexWeight (SCALE - v and v).
 *
 * <p>It has its own key, so it sits next to the Water mod HUD (key WaterOfArrakis) without touching it.
 */
final class HudView extends CustomUIHud {

    static final String KEY = "EquipmentOfArrakisBars";
    private static final String DOCUMENT = "Hud/Equipment_of_Arrakis/Hud/Arrakis_Hud.ui";

    private final HudConfig config;
    private final boolean rightHalf;
    private final double[] sentPercent = new double[HudBar.values().length];
    private final String[] sentColor = new String[HudBar.values().length];

    /** {@code rightHalf} false: the Water mod is not there, so the Heat Exposure and Water bars are not drawn. */
    HudView(PlayerRef playerRef, HudConfig config, boolean rightHalf) {
        super(playerRef, KEY);
        this.config = config;
        this.rightHalf = rightHalf;
    }

    @Override
    protected void build(UICommandBuilder ui) {
        ui.append(DOCUMENT);
        // A fresh document starts at its defaults on the client: forget what was sent before.
        java.util.Arrays.fill(sentPercent, Double.NaN);
        java.util.Arrays.fill(sentColor, null);

        int thickness = px(config.getBarThickness());
        int lift = px(config.getBarsLift());
        int icon = px(config.getIconSize());
        for (HudBar bar : HudBar.values()) {
            String n = bar.id;
            int bottom = px(config.getBottomRowBottom()) + (bar.topRow ? px(config.getRowPitch()) : 0) + lift;
            int outer = px(bar.topRow ? config.getTopOuter() : config.getBottomOuter());
            int inner = px(config.getInnerGap());
            ui.setObject("#" + n + "Row.Anchor", row(bottom, thickness));
            ui.setObject("#" + n + "Track.Anchor", width(Math.max(1, outer - inner)));
            ui.setObject("#" + n + "Pad.Anchor", width(inner));
            int iconBottom = bottom + (int) Math.round((thickness - icon) / 2.0);
            ui.setObject("#" + n + "IconRow.Anchor", row(iconBottom, icon));
            ui.setObject("#" + n + "Icon.Anchor", size(icon, icon));
            int centre = px(bar.topRow ? config.getTopIconCentre() : config.getBottomIconCentre());
            ui.setObject("#" + n + "IconPad.Anchor", width(Math.max(0, centre - icon / 2)));
            ui.set("#" + n + "Empty.FlexWeight", HudMath.SCALE);
            ui.set("#" + n + "Fill.FlexWeight", 0);
            String color = baseColor(bar);
            ui.set("#" + n + "Fill.Background.Color", color);
            sentColor[bar.ordinal()] = color;
            boolean shown = bar.left || rightHalf;
            ui.set("#" + n + "Row.Visible", shown);
            ui.set("#" + n + "IconRow.Visible", shown);
        }
    }

    private String baseColor(HudBar bar) {
        return switch (bar) {
            case POWER -> config.getPowerColor();
            case HEALTH -> config.getHealthColor();
            case WATER -> config.getWaterColor();
            case EXPOSURE -> HudMath.exposureColor(0, config.getExposureRedStartPercent(), config.getExposureColorOrange(), config.getExposureColorRed());
        };
    }

    /**
     * Sends the new fill lengths and colours, but only what changed by enough to be seen. {@code percent[i]} is the value of bar i
     * (NaN: not drawn), {@code colors[i]} its colour now (flash and exposure colour already applied).
     */
    void refresh(double[] percent, String[] colors) {
        double min = config.getMinPercentChange();
        UICommandBuilder ui = null;
        for (HudBar bar : HudBar.values()) {
            int i = bar.ordinal();
            if (Double.isNaN(percent[i])) {
                continue;
            }
            boolean fillChanged = HudMath.changed(sentPercent[i], percent[i], min);
            boolean colorChanged = colors[i] != null && !colors[i].equals(sentColor[i]);
            if (!fillChanged && !colorChanged) {
                continue;
            }
            if (ui == null) {
                ui = new UICommandBuilder();
            }
            if (fillChanged) {
                int[] s = HudMath.split(percent[i]);
                ui.set("#" + bar.id + "Empty.FlexWeight", s[0]);
                ui.set("#" + bar.id + "Fill.FlexWeight", s[1]);
                sentPercent[i] = percent[i];
            }
            if (colorChanged) {
                ui.set("#" + bar.id + "Fill.Background.Color", colors[i]);
                sentColor[i] = colors[i];
            }
        }
        if (ui != null) {
            update(false, ui);
        }
    }

    private static int px(double value) {
        return (int) Math.round(value);
    }

    private static Anchor row(int bottom, int height) {
        Anchor a = new Anchor();
        a.setLeft(Value.of(0));
        a.setRight(Value.of(0));
        a.setBottom(Value.of(bottom));
        a.setHeight(Value.of(height));
        return a;
    }

    private static Anchor width(int width) {
        Anchor a = new Anchor();
        a.setWidth(Value.of(width));
        return a;
    }

    private static Anchor size(int width, int height) {
        Anchor a = new Anchor();
        a.setWidth(Value.of(width));
        a.setHeight(Value.of(height));
        return a;
    }
}
