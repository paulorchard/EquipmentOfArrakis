// EXPERIMENT: delete with the whole experiments module (see EXPERIMENT_LOG.md, "Removing the experiments").
//
// The particle systems of the calibration rigs (/arrakis exp cal ...), under Server/Particles/Equipment_of_Arrakis/Experiments/Calibration:
//   Arrakis_Exp_Cal_Dot      one small white dot that lives 0.15 s: the collapse test spawns rows of them in world space
//   Arrakis_Exp_Cal_Mark     a magenta cross of seven dots: the target marker
//   Arrakis_Exp_Cal_Ruler    dots along the local Z of a node, 10 blocks each way (small dots on the + side, big on the - side),
//                            long-lived, no velocity, turning with the node; the colour comes from the ModelParticle
//   Arrakis_Exp_Cal_Stream   a fine straight stream along the local -Z (the way the flame points), 10 blocks long, for the beam rig
// Vanilla texture Particles/Textures/Basic/Glow.png, by path.
//
//   node tools/assets/experiments/make_calibration_particles.js
const fs = require('fs');
const path = require('path');

const TEXTURE = 'Particles/Textures/Basic/Glow.png';
const root = path.join(__dirname, '..', '..', '..', 'src', 'main', 'resources', 'Server', 'Particles', 'Equipment_of_Arrakis', 'Experiments', 'Calibration');
const marker = 'EXPERIMENT: delete with the whole experiments module (see EXPERIMENT_LOG.md, "Removing the experiments"). ';
function write(relative, json) {
    const file = path.join(root, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n');
}
const range = (min, max) => ({ Min: min, Max: max });
const scale = v => ({ X: range(v, v), Y: range(v, v) });

function spawner(note, o) {
    return Object.assign({
        $Comment: marker + note + ' Generated by tools/assets/experiments/make_calibration_particles.js.',
        RenderMode: 'BlendAdd',
        ParticleRotationInfluence: 'Billboard',
        LinearFiltering: true,
        LightInfluence: 0.0,
        ParticleRotateWithSpawner: true,
        InitialVelocity: {},
        Particle: {
            Texture: TEXTURE,
            FrameSize: { Width: 32, Height: 32 },
            ScaleRatioConstraint: 'OneToOne',
            Animation: { 0: { FrameIndex: range(0, 0), Opacity: 1, Color: o.color || '#ffffff', Scale: scale(1) }, 100: { Opacity: 1 } },
            InitialAnimationFrame: { FrameIndex: range(0, 0), Opacity: 1, Scale: scale(o.size) },
            SoftParticles: 'Disable',
        },
    }, o.fields);
}
const burst = { SpawnBurst: true, SpawnRate: range(1, 1), TotalParticles: range(1, 1), MaxConcurrentParticles: 2 };

write('Spawners/Arrakis_Exp_Cal_Dot.particlespawner', spawner('One small white dot for 0.15 s.', {
    size: 0.05, fields: Object.assign({ ParticleLifeSpan: range(0.15, 0.15) }, burst) }));
write('Arrakis_Exp_Cal_Dot.particlesystem', { $Comment: marker + 'One small white dot.', Spawners: [{ SpawnerId: 'Arrakis_Exp_Cal_Dot' }], LifeSpan: 0.2, CullDistance: 100.0, IsImportant: false });

write('Spawners/Arrakis_Exp_Cal_Mark.particlespawner', spawner('A magenta dot of the target marker.', {
    size: 0.07, color: '#ff40ff', fields: Object.assign({ ParticleLifeSpan: range(0.25, 0.25) }, burst) }));
const arm = 0.16;
write('Arrakis_Exp_Cal_Mark.particlesystem', {
    $Comment: marker + 'The target marker: a magenta cross of seven dots.',
    Spawners: [{ SpawnerId: 'Arrakis_Exp_Cal_Mark' }].concat([[arm, 0, 0], [-arm, 0, 0], [0, arm, 0], [0, -arm, 0], [0, 0, arm], [0, 0, -arm]]
        .map(([X, Y, Z]) => ({ SpawnerId: 'Arrakis_Exp_Cal_Mark', PositionOffset: { X, Y, Z } }))),
    LifeSpan: 0.3, CullDistance: 100.0, IsImportant: false });

write('Spawners/Arrakis_Exp_Cal_Ruler_Plus.particlespawner', spawner('Small dots along +Z, 0 to 10 blocks.', {
    size: 0.06, fields: { MaxConcurrentParticles: 80, ParticleLifeSpan: range(0.8, 0.8), SpawnRate: range(60, 60), EmitOffset: { Z: range(0, 10) } } }));
write('Spawners/Arrakis_Exp_Cal_Ruler_Minus.particlespawner', spawner('Big dots along -Z, 0 to 10 blocks.', {
    size: 0.14, fields: { MaxConcurrentParticles: 80, ParticleLifeSpan: range(0.8, 0.8), SpawnRate: range(30, 30), EmitOffset: { Z: range(-10, 0) } } }));
write('Arrakis_Exp_Cal_Ruler.particlesystem', { $Comment: marker + 'A ruler along the local Z of a node: small dots on the + side, big dots on the - side. Coloured by the ModelParticle.',
    Spawners: [{ SpawnerId: 'Arrakis_Exp_Cal_Ruler_Plus' }, { SpawnerId: 'Arrakis_Exp_Cal_Ruler_Minus' }], LifeSpan: 0.6, CullDistance: 100.0, IsImportant: false });

write('Spawners/Arrakis_Exp_Cal_Stream.particlespawner', spawner('A fine straight stream along -Z: speed 25, life 0.4 s, 10 blocks.', {
    size: 0.04, color: '#fff3b0', fields: { MaxConcurrentParticles: 80, ParticleLifeSpan: range(0.4, 0.4), SpawnRate: range(160, 160),
        InitialVelocity: { Speed: range(25, 25), Yaw: range(0, 0), Pitch: range(0, 0) } } }));
write('Arrakis_Exp_Cal_Stream.particlesystem', { $Comment: marker + 'A fine straight stream, 10 blocks long, for the beam rig.', Spawners: [{ SpawnerId: 'Arrakis_Exp_Cal_Stream' }], LifeSpan: 0.6, CullDistance: 100.0, IsImportant: false });
console.log('wrote the calibration particle systems');
