// Experiment 2, the Flame Beam Cutter: the Flame Cutter with the Stoneskin wand's laser (the vanilla particle system NatureBeam, by id)
// in place of the focusing ring of dots, and a static weapon (no firing animation in either view). Writes the item, its root
// interaction and the "look" interaction whose Particles and FirstPersonParticles come from tools/assets/experiments/calibration.json,
// the block that `/arrakis exp cal show` prints. Applying a new calibration is: replace calibration.json, run this, rebuild.
//
//   node tools/assets/experiments/make_flame_beam.js
const fs = require('fs');
const path = require('path');

const calibration = JSON.parse(fs.readFileSync(path.join(__dirname, 'calibration.json'), 'utf8'));
const SYSTEM = 'NatureBeam';
const RUN_TIME = 0.1; // the same as the tick: the beam is renewed with every tick while the button is held

const res = path.join(__dirname, '..', '..', '..', 'src', 'main', 'resources');
const marker = 'EXPERIMENT: delete with the whole experiments module (see EXPERIMENT_LOG.md, "Removing the experiments"). ';
function write(relative, json) {
    const file = path.join(res, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n');
}

function entry(view) {
    const e = { SystemId: SYSTEM };
    if (view.detached) {
        e.DetachedFromModel = true;
    }
    e.TargetEntityPart = 'Entity';
    e.TargetNodeName = view.node;
    e.PositionOffset = { X: view.x, Y: view.y, Z: view.z };
    e.RotationOffset = { Yaw: view.yaw, Pitch: view.pitch, Roll: view.roll };
    if (view.scale !== 1) {
        e.Scale = view.scale;
    }
    return e;
}

write('Server/Item/Interactions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Beam_Look.json', {
    $Comment: marker + 'The look of the Flame Beam Cutter: the vanilla NatureBeam (Stoneskin wand, Server/Particles/_Test/NatureRnD, a test folder an update may remove) placed from tools/assets/experiments/calibration.json (apex ' + calibration.apex + '). No animation, so the weapon stays in its hold pose. It runs only when the tick before it did not refuse. Generated by tools/assets/experiments/make_flame_beam.js.',
    Type: 'Simple',
    RunTime: RUN_TIME,
    Effects: { Particles: [entry(calibration.tp)], FirstPersonParticles: [entry(calibration.fp)] },
});
write('Server/Item/RootInteractions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Beam_Primary.json', {
    $Comment: marker + 'Primary of the Flame Beam Cutter: the tick of the Flame Cutter (Mana, range 5, cutting; it refuses the whole chain without Mana), then the laser.',
    Interactions: ['Arrakis_Exp_Cutter_Tick', 'Arrakis_Exp_Flame_Beam_Look'],
    Tags: { Attack: ['Ranged'] },
});
const item = JSON.parse(fs.readFileSync(path.join(res, 'Server/Item/Items/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Cutter.json'), 'utf8'));
item.$Comment = marker + 'Experiment 2, the Flame Beam Cutter: a duplicate of Arrakis_Exp_Flame_Cutter (same model, texture copy, animations, tags, tick) whose look is the Stoneskin laser instead of the ring of dots, with no firing animation. Generated by tools/assets/experiments/make_flame_beam.js.';
item.TranslationProperties = { Name: 'server.items.Arrakis_Exp_Flame_Beam.name', Description: 'server.items.Arrakis_Exp_Flame_Beam.description' };
item.Interactions = { Primary: 'Arrakis_Exp_Flame_Beam_Primary' };
write('Server/Item/Items/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Beam.json', item);
console.log('wrote the Flame Beam Cutter: first person at ' + calibration.fp.node + ' (' + calibration.fp.x + ', ' + calibration.fp.y + ', ' + calibration.fp.z
    + '), third person at ' + calibration.tp.node + ' (' + calibration.tp.x + ', ' + calibration.tp.y + ', ' + calibration.tp.z + ')');
