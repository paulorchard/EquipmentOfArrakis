// EXPERIMENT: delete with the whole experiments module (see EXPERIMENT_LOG.md, "Removing the experiments").
//
// Experiment 2, the Flame Beam Cutter: the Flame Cutter with the Stoneskin wand's laser (the vanilla particle system NatureBeam, by id)
// in place of the focusing ring of dots (spawned by the server in world space from the muzzle to the look target), and a static weapon (no firing animation in either view). Writes the item, its root
// interaction, the spawn interaction (Arrakis_Exp_Beam_Spawn, Java) with the numbers of tools/assets/experiments/calibration.json (the "cam" start,
// the apex, endAtBlock), and the pace; the file is the block that `/arrakis exp cal show` prints. Applying a new calibration is: replace calibration.json, run this, rebuild.
//
//   node tools/assets/experiments/make_flame_beam.js
const fs = require('fs');
const path = require('path');

const calibration = JSON.parse(fs.readFileSync(path.join(__dirname, 'calibration.json'), 'utf8'));
const SYSTEM = 'NatureBeam';
// The NatureBeam is made for ONE cast (vanilla Stoneskin_Cast: RunTime 0.2, the system emits for that long): its streak (NatureBeam_Beam and _Overlay) is a burst
// with WaveDelay 0.1 s and a life of 0.2 s that fades in over its first 15-50 %, so the system must run for about 0.2 s or the streak never appears (a 0.05 s
// duration showed it for 2 frames). Casting again every 0.1 s overlaps two of them, which is what pressing the button rapidly does: an always-on beam.
const RUN_TIME = 0.1; // the pace of the Flame Beam Cutter: a new cast every 0.1 s while the button is held
const DURATION = 0.2; // seconds each cast emits: the vanilla cast time
const TICK_ID = 'Arrakis_Exp_Flame_Beam_Tick'; // the Mana / cutting tick at that pace (same rates per second as Arrakis_Exp_Cutter_Tick)
const FLAME_RUN_TIME = 0.1; // the Flame Cutter keeps its pace and its Burn animation
const FLAME_DURATION = 0.14;
const FLAME_END_OFFSET = 3.8; // RANGE - MUZZLE of make_flame_focus.js: the focus of the ring is that far in front of the system's origin
const END_OFFSET = 1.8; // blocks in front of the NatureBeam's origin where its end burst sits (measure_nature_beam.js)

const res = path.join(__dirname, '..', '..', '..', 'src', 'main', 'resources');
const marker = 'EXPERIMENT: delete with the whole experiments module (see EXPERIMENT_LOG.md, "Removing the experiments"). ';
function write(relative, json) {
    const file = path.join(res, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n');
}

const cam = calibration.cam;
write('Server/Item/Interactions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Beam_Spawn.json', {
    $Comment: marker + 'The laser of the Flame Beam Cutter, spawned by the server in world space every tick: it starts at (Right, Up, Forward) = (' + cam.x + ', ' + cam.y + ', ' + cam.z + ') in the camera frame and ends where the look ray lands (' + (calibration.endAtBlock ? 'the block it enters' : 'apex ' + calibration.apex + ' blocks') + '), so its vanishing point is the look target by construction. From tools/assets/experiments/calibration.json. Generated by tools/assets/experiments/make_flame_beam.js.',
    Type: 'Arrakis_Exp_Beam_Spawn',
    System: SYSTEM,
    Right: cam.x,
    Up: cam.y,
    Forward: cam.z,
    Apex: calibration.apex,
    EndAtBlock: !!calibration.endAtBlock,
    EndOffset: END_OFFSET,
    Duration: DURATION,
    Scale: cam.scale,
    Frame: 'Camera',
    Glow: true,
    PulseHz: calibration.pulseHz === undefined ? 2 : calibration.pulseHz,
});
// the same tick at the beam's pace: the same Mana and the same cutting per second, in smaller steps
const tick = JSON.parse(fs.readFileSync(path.join(res, 'Server/Item/Interactions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Cutter_Tick.json'), 'utf8'));
tick.$Comment = marker + 'Arrakis_Exp_Cutter_Tick at the pace of the Flame Beam Cutter (one server tick): the same Mana and the same cutting per second, in steps of RunTime. Generated by tools/assets/experiments/make_flame_beam.js.';
tick.DamageScale = +(tick.DamageScale * RUN_TIME / tick.RunTime).toFixed(5);
tick.RunTime = RUN_TIME;
write('Server/Item/Interactions/Equipment_of_Arrakis/Experiments/' + TICK_ID + '.json', tick);
// the Flame Cutter: the ring of dots spawned by the server from the grip (the body frame) to the look target
const body = calibration.body || { x: 0.275, y: -0.324, z: 0.45, scale: 1 };
write('Server/Item/Interactions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Spawn.json', {
    $Comment: marker + 'The focusing ring of the Flame Cutter, spawned by the server in world space every pass: it starts at the grip (right ' + body.x + ', up ' + body.y + ' from the eye, forward ' + body.z + ' along the heading of the body) and its focus is the look target, so it ends on the crosshair in both views. From tools/assets/experiments/calibration.json. Generated by tools/assets/experiments/make_flame_beam.js.',
    Type: 'Arrakis_Exp_Beam_Spawn',
    System: 'Arrakis_Exp_Flame_Focus',
    Right: body.x,
    Up: body.y,
    Forward: body.z,
    Apex: calibration.apex,
    EndAtBlock: !!calibration.endAtBlock,
    EndOffset: FLAME_END_OFFSET,
    Duration: FLAME_DURATION,
    Scale: body.scale === undefined ? 1 : body.scale,
    Frame: 'Body',
});
write('Server/Item/Interactions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Burn.json', {
    $Comment: marker + 'The animation of the Flame Cutter: the vanilla Burn animation of Goblin_Flamethrower. The ring of dots is Arrakis_Exp_Flame_Spawn (world space), not particles on the model. Runs only when the tick before it did not refuse.',
    Type: 'Simple',
    RunTime: FLAME_RUN_TIME,
    Effects: { ItemPlayerAnimationsId: 'Goblin_Flamethrower', ItemAnimationId: 'Burn', ClearAnimationOnFinish: true },
});
write('Server/Item/RootInteractions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Primary.json', {
    $Comment: marker + 'Primary of the Flame Cutter: the tick first (it refuses the whole chain when there is no Mana, so nothing below it starts), then the focusing ring spawned by the server, then the burn animation. No fire, no damage, no sound.',
    Interactions: ['Arrakis_Exp_Cutter_Tick', 'Arrakis_Exp_Flame_Spawn', 'Arrakis_Exp_Flame_Burn'],
    Tags: { Attack: ['Ranged'] },
});
write('Server/Item/Interactions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Beam_Pace.json', {
    $Comment: marker + 'Keeps the Primary chain of the Flame Beam Cutter running at the pace of the tick: no effects, no animation, so the weapon stays in its hold pose.',
    Type: 'Simple',
    RunTime: RUN_TIME,
});
write('Server/Item/RootInteractions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Beam_Primary.json', {
    $Comment: marker + 'Primary of the Flame Beam Cutter: the tick at the pace of the beam (Mana, range 5, cutting; it refuses the whole chain without Mana), then the laser and its pulsing glow spawned by the server, then the pace.',
    Interactions: [TICK_ID, 'Arrakis_Exp_Flame_Beam_Spawn', 'Arrakis_Exp_Flame_Beam_Pace'],
    Tags: { Attack: ['Ranged'] },
});
const item = JSON.parse(fs.readFileSync(path.join(res, 'Server/Item/Items/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Cutter.json'), 'utf8'));
item.$Comment = marker + 'Experiment 2, the Flame Beam Cutter: a duplicate of Arrakis_Exp_Flame_Cutter (same model, texture copy, animations, tags, tick) whose look is the Stoneskin laser instead of the ring of dots, with no firing animation. Generated by tools/assets/experiments/make_flame_beam.js.';
item.TranslationProperties = { Name: 'server.items.Arrakis_Exp_Flame_Beam.name', Description: 'server.items.Arrakis_Exp_Flame_Beam.description' };
item.Interactions = { Primary: 'Arrakis_Exp_Flame_Beam_Primary' };
write('Server/Item/Items/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Flame_Beam.json', item);
console.log('wrote the Flame Beam Cutter: first person at ' + calibration.fp.node + ' (' + calibration.fp.x + ', ' + calibration.fp.y + ', ' + calibration.fp.z
    + '), third person at ' + calibration.tp.node + ' (' + calibration.tp.x + ', ' + calibration.tp.y + ', ' + calibration.tp.z + ')');
