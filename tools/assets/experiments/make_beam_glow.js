// EXPERIMENT: delete with the whole experiments module (see EXPERIMENT_LOG.md, "Removing the experiments").
//
// The glow around the Flame Beam Cutter's laser: LEVELS particle systems, Arrakis_Exp_Beam_Glow_0 (dim) to Arrakis_Exp_Beam_Glow_<LEVELS-1>
// (bright). Each is a soft halo: big round glow sprites released on a thin ring (HALO_RADIUS) around the axis and flown along it, so that
// together they make a tube of light as long as the laser (SPEED * LIFE blocks). The server spawns ONE of them with every laser (the interaction
// Arrakis_Exp_Beam_Spawn, Glow true) and picks the level from a sine of the time (PulseHz cycles a second), so the glow pulsates by changing
// level; the level is the only difference between the systems, which is why a pulse does not stretch the halo (a scale pulse would also scale its length).
//
// The emission is along the system's -Z, as the vanilla flame and the NatureBeam are; the server turns the system to the look line.
//
//   node tools/assets/experiments/make_beam_glow.js
const fs = require('fs');
const path = require('path');

// ---- the look: change these and run the script again
const LEVELS = 4;                 // must be ExpBeamSpawnInteraction.GLOW_LEVELS
const OPACITY = [0.05, 0.09, 0.15, 0.24]; // opacity of one sprite at each level; the sprites overlap, so the halo is several times this
const HALO_RADIUS = 0.1;          // blocks: the ring the sprites leave on
const SIZE = 0.5;                 // blocks: width of a sprite
const COLOR = '#79e07a';          // the green of the NatureBeam (#346830 is its dark core)
const SPEED = 22.5;               // blocks a second along the axis
const LIFE = 0.2;                 // seconds: SPEED * LIFE = 4.5 blocks, the length of the NatureBeam; a cast lasts 0.2 s and is repeated every 0.1 s
const SPAWN_RATE = 500;           // sprites a second
const TEXTURE = 'Particles/Textures/Basic/Glow.png'; // vanilla, by path

if (OPACITY.length !== LEVELS) throw new Error('one opacity for each level');

const marker = 'EXPERIMENT: delete with the whole experiments module (see EXPERIMENT_LOG.md, "Removing the experiments"). ';
const root = path.join(__dirname, '..', '..', '..', 'src', 'main', 'resources', 'Server', 'Particles', 'Equipment_of_Arrakis', 'Experiments');
function write(relative, json) {
    const file = path.join(root, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n');
}
const range = (min, max) => ({ Min: min, Max: max });
const scale = v => ({ X: range(v, v), Y: range(v, v) });

for (let level = 0; level < LEVELS; level++) {
    const id = 'Arrakis_Exp_Beam_Glow_' + level;
    write('Spawners/' + id + '.particlespawner', {
        $Comment: marker + 'Level ' + level + ' of ' + (LEVELS - 1) + ' of the pulsing halo around the Flame Beam Cutter laser (sprite opacity ' + OPACITY[level] + '). Generated by tools/assets/experiments/make_beam_glow.js.',
        RenderMode: 'BlendAdd',
        ParticleRotationInfluence: 'Billboard',
        LinearFiltering: true,
        LightInfluence: 0.0,
        ParticleRotateWithSpawner: true,
        MaxConcurrentParticles: Math.ceil(SPAWN_RATE * LIFE * 1.5) + 4,
        ParticleLifeSpan: range(LIFE, LIFE),
        SpawnRate: range(SPAWN_RATE, SPAWN_RATE),
        SpawnBurst: false,
        Shape: 'Sphere',
        // two ranges with Min = Max: the rim of a 2D form, i.e. a ring around the axis (as in make_flame_focus.js)
        EmitOffset: { X: range(HALO_RADIUS, HALO_RADIUS), Y: range(HALO_RADIUS, HALO_RADIUS) },
        UseEmitDirection: false,
        InitialVelocity: { Speed: range(SPEED, SPEED), Yaw: range(0, 0), Pitch: range(0, 0) },
        Particle: {
            Texture: TEXTURE,
            FrameSize: { Width: 32, Height: 32 },
            ScaleRatioConstraint: 'OneToOne',
            // fades in and out over the life, so that a sprite never pops
            Animation: {
                0: { FrameIndex: range(0, 0), Opacity: 0, Color: COLOR, Scale: scale(1) },
                20: { Opacity: OPACITY[level] },
                80: { Opacity: OPACITY[level] },
                100: { Opacity: 0 },
            },
            InitialAnimationFrame: { FrameIndex: range(0, 0), Opacity: OPACITY[level], Scale: scale(SIZE) },
            SoftParticles: 'Disable',
        },
    });
    write(id + '.particlesystem', {
        $Comment: marker + 'Level ' + level + ' of the pulsing halo around the Flame Beam Cutter laser. Generated by tools/assets/experiments/make_beam_glow.js.',
        Spawners: [{ SpawnerId: id }],
        LifeSpan: 0.3,
        CullDistance: 100.0,
        IsImportant: false,
    });
}
console.log('wrote ' + LEVELS + ' glow levels, ' + (SPEED * LIFE).toFixed(1) + ' blocks long, opacities ' + OPACITY.join(', '));
