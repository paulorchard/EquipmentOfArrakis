// Experiment 2, the Drill Cutter: writes the item Arrakis_Exp_Drill_Cutter and the beam interaction Arrakis_Exp_Drill_Beam.
//
//  * The item is a clone of Tool_Drill_Scrap (same model, texture, animations, icon, tags, drop animation, icon properties, as
//    paths into the vanilla assets) with, as data: the Tool.Specs of the strongest pickaxe (copied from the unzipped assets, so
//    that they follow the game's numbers), a single-block break shape, no durability (no MaxDurability, no DurabilityLossBlockTypes),
//    a use distance of RANGE for every game mode, no recipe, no sound set, and Primary and Secondary on Arrakis_Exp_Drill_Mine.
//  * The beam interaction carries the Stoneskin wand's laser: the vanilla particle system NatureBeam, by id, with the same two
//    entries as Stoneskin_Cast (third person on the Head node, first person on the Body node), moved along the beam with BEAM_Z so
//    that its end burst sits at RANGE blocks. BEAM_COLOR is the entry's Color knob (null = the vanilla green).
//
//   unzip -o -q "$APPDATA/Hytale/install/release/package/game/latest/Assets.zip" "Server/Item/Items/Tool/Pickaxe/*" -d <dir>
//   node tools/assets/experiments/make_drill_cutter.js <dir>
const fs = require('fs');
const path = require('path');

// ---- settings
const RANGE = 5;                  // blocks: the use distance of the item, and where the beam's end should sit
const STAND_IN = 'Tool_Pickaxe_Mithril';
const BEAM_Z = 3.2;               // how far along the beam the system is placed (vanilla Stoneskin: 3.2 third person, 3 first person).
                                  // measure_nature_beam.js: the end burst of the beam is centred at Z + 1.77, so 3.2 puts it at 4.97
const BEAM_THIRD = { X: -0.5, Z: BEAM_Z };          // vanilla: X -0.5, Z 3.2, node Head
const BEAM_FIRST = { X: -0.2, Y: 1.5, Z: BEAM_Z };  // vanilla: X -0.2, Y 1.5, Z 3, node Body
const BEAM_COLOR = null;          // e.g. '#ffb347' (amber) or '#9fd8ff' (white-blue); null leaves the vanilla green
const SWING_SECONDS = 0.3;        // how long the beam interaction lasts: the item's cooldown, so the beam is continuous while held

const res = path.join(__dirname, '..', '..', '..', 'src', 'main', 'resources');
const marker = 'EXPERIMENT: delete with the whole experiments module (see EXPERIMENT_LOG.md, "Removing the experiments"). ';
const dir = path.join(process.argv[2] || '.', 'Server/Item/Items/Tool/Pickaxe');
const pickaxe = JSON.parse(fs.readFileSync(path.join(dir, STAND_IN + '.json'), 'utf8'));
if (!pickaxe.Tool || !pickaxe.Tool.Specs) {
    throw new Error(STAND_IN + ' has no Tool.Specs of its own');
}

function write(relative, json) {
    const file = path.join(res, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n');
}

write('Server/Item/Items/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Drill_Cutter.json', {
    $Comment: marker + 'Experiment 2, the Drill Cutter: a clone of Tool_Drill_Scrap (same model, texture, animations, icon, tags) that mines through the engine\'s own BreakBlock with the Specs of ' + STAND_IN + ' (copied as data), one block at a time, no durability, use distance ' + RANGE + ', no recipe, no sound set. Generated by tools/assets/experiments/make_drill_cutter.js.',
    TranslationProperties: {
        Name: 'server.items.Arrakis_Exp_Drill_Cutter.name',
        Description: 'server.items.Arrakis_Exp_Drill_Cutter.description',
    },
    Categories: ['IslandCraft.Tools'],
    Icon: 'Icons/ItemsGenerated/Tool_Drill_Scrap.png',
    Model: 'NPC/Intelligent/Goblin/Models/Weapons/Drill/Scrap.blockymodel',
    Texture: 'NPC/Intelligent/Goblin/Models/Weapons/Drill/Scrap_Texture.png',
    PlayerAnimationsId: 'Drill',
    Tool: {
        BreakShape: { Id: 'Box', Centered: true, Depth: 1, Height: 1, Width: 1, Orientation: 'View', Offset: { X: 0, Y: 0, Z: 0 } },
        BreakShapeDurabilityMode: 'PerBlock',
        Specs: pickaxe.Tool.Specs,
    },
    InteractionConfig: { UseDistance: { Adventure: RANGE, Creative: RANGE } },
    Interactions: { Primary: 'Arrakis_Exp_Drill_Mine', Secondary: 'Arrakis_Exp_Drill_Mine' },
    IconProperties: { Scale: 0.38, Rotation: [315, 90, 0], Translation: [-24, -42] },
    DroppedItemAnimation: 'Items/Animations/Dropped/Dropped_Diagonal_Left.blockyanim',
    Tags: { Type: ['Tool'] },
});

const third = { SystemId: 'NatureBeam', DetachedFromModel: true, PositionOffset: BEAM_THIRD, TargetEntityPart: 'Entity', TargetNodeName: 'Head', RotationOffset: { Pitch: 180 } };
const first = { SystemId: 'NatureBeam', TargetEntityPart: 'Entity', TargetNodeName: 'Body', PositionOffset: BEAM_FIRST, RotationOffset: { Pitch: 180 } };
if (BEAM_COLOR) {
    third.Color = BEAM_COLOR;
    first.Color = BEAM_COLOR;
}
write('Server/Item/Interactions/Equipment_of_Arrakis/Experiments/Arrakis_Exp_Drill_Beam.json', {
    $Comment: marker + 'The laser of the Drill Cutter: the vanilla NatureBeam (Stoneskin wand, Server/Particles/_Test/NatureRnD; a test folder, so it may vanish in an update) placed so that its end burst is ' + RANGE + ' blocks out. Lasts one swing so that it is continuous while held, and runs only when the Mana gate before it passed. Generated by tools/assets/experiments/make_drill_cutter.js.',
    Type: 'Simple',
    RunTime: SWING_SECONDS,
    Effects: { Particles: [third], FirstPersonParticles: [first] },
});
console.log('wrote the item with ' + pickaxe.Tool.Specs.length + ' specs of ' + STAND_IN + ' and the beam at Z ' + BEAM_Z
    + (BEAM_COLOR ? ', tinted ' + BEAM_COLOR : ', untinted'));
