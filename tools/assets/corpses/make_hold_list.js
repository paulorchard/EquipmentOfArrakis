// Writes the list of vanilla models whose Death clip does NOT hold its last keyframe (a body of such a mob stands back up when the clip ends),
// to src/main/resources/corpses_nonholding_models.txt. The mod reads the clips itself at run time; this list is the fallback for when the
// server cannot read the common asset bytes, and the documentation of which models are affected.
//   node tools/assets/corpses/make_hold_list.js        (needs `unzip` on the PATH, like the HUD generator)
//   HUD_ASSETS_ZIP=<...\Assets.zip> overrides the default install path.
// A model is listed when any clip of its "Death" animation set has holdLastKeyframe false (or no such key). A model with a "Parent" takes the
// parent's animation sets it does not define itself.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ZIP = process.env.HUD_ASSETS_ZIP
    || path.join(process.env.APPDATA, 'Hytale', 'install', 'release', 'package', 'game', 'latest', 'Assets.zip');
const OUT = path.join(__dirname, '..', '..', '..', 'src', 'main', 'resources', 'corpses_nonholding_models.txt');

const entry = name => execFileSync('unzip', ['-p', ZIP, name], { maxBuffer: 1 << 26 }).toString('utf8');
const names = execFileSync('unzip', ['-Z1', ZIP], { maxBuffer: 1 << 26 }).toString('utf8').split(/\r?\n/);

const models = {};
for (const name of names) {
    const m = /^Server\/Models\/(?:.*\/)?([^/]+)\.json$/.exec(name);
    if (m) {
        try {
            models[m[1]] = JSON.parse(entry(name));
        } catch (e) {
            console.error('skipped ' + name + ': ' + e.message);
        }
    }
}

function deathSet(id, depth) {
    const model = models[id];
    if (!model || depth > 8) return null;
    if (model.AnimationSets && model.AnimationSets.Death) return model.AnimationSets.Death;
    return model.Parent ? deathSet(model.Parent, depth + 1) : null;
}

const holdCache = {};
function holds(clip) {
    if (!(clip in holdCache)) {
        let text = null;
        for (const candidate of ['Common/' + clip, clip]) {
            try {
                text = entry(candidate);
                break;
            } catch (e) {
                // try the next spelling
            }
        }
        const m = text && /"holdLastKeyframe"\s*:\s*(true|false)/.exec(text);
        holdCache[clip] = m ? m[1] === 'true' : false;
    }
    return holdCache[clip];
}

const listed = [];
let withDeath = 0;
for (const id of Object.keys(models).sort()) {
    const set = deathSet(id, 0);
    if (!set || !set.Animations || set.Animations.length === 0) continue;
    withDeath++;
    if (!set.Animations.every(a => a.Animation && holds(a.Animation))) listed.push(id);
}
const lines = [
    '# Models whose Death clip does not hold its last keyframe. Generated by tools/assets/corpses/make_hold_list.js; do not edit.',
    '# The mod reads the clips at run time and uses this list only when it cannot.',
    ...listed,
];
fs.writeFileSync(OUT, lines.join('\n') + '\n');
console.log(withDeath + ' models with a Death set, ' + listed.length + ' do not hold: ' + listed.join(', '));
